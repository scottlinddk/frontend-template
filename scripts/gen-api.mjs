// Generates src/shared/api/schema.d.ts from an OpenAPI document.
//
//   vp run gen:api                         uses openapi/openapi.json
//   OPENAPI_SPEC=https://host/openapi.json vp run gen:api
//
// The output is committed so installs need no network and API changes show up
// in review. CI re-runs this task and fails if the committed file is stale.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(import.meta.dirname, "..");
const spec = process.env.OPENAPI_SPEC ?? "openapi/openapi.json";
const output = resolve(root, "src/shared/api/schema.d.ts");

const source = /^https?:\/\//.test(spec) ? new URL(spec) : pathToFileURL(resolve(root, spec));
const ast = await openapiTS(source);

const banner = `/* eslint-disable */\n// Generated by scripts/gen-api.mjs from ${spec}. Do not edit by hand.\n\n`;
await mkdir(dirname(output), { recursive: true });
await writeFile(output, banner + astToString(ast));
console.log(`Wrote ${output} from ${spec}`);
